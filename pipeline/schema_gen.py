PRIMARY_KEYS = {
    "documents": ["doc_key"],
    "facts": ["fact_key"],
    "observations": ["obs_key"],
    "entities": ["entity_id", "record_kind", "ref", "valid_from"],
    "links": ["link_key"],
    "measures": ["measure", "subject", "counterparty", "period_start", "period_end", "view",
                 "as_of", "term", "breakdown_key", "financing_policy", "constant_perimeter",
                 "variant"],
    "controls": ["control", "subject", "period_start", "period_end", "view", "as_of",
                 "breakdown_key", "mapping_variant"],
    "exclusions": ["exclusion_key"],
}


def render():
    out = ["-- schema.sql — engendré par python -m pipeline.schema_gen depuis pipeline/registry.py.",
           "-- Ne pas éditer à la main : une valeur absente d'une énumération n'existe pas (§0).",
           ""]
    for name, values in ENUMS.items():
        vals = ", ".join("'" + v.replace("'", "''") + "'" for v in values)
        out.append(f"CREATE TYPE {name} AS ENUM ({vals});")
    out.append("")
    pairs = ", ".join(f"'{p}'" for p in measure_term_pairs())
    measures = ", ".join(f"'{m}'" for m in MEASURES)
    for table, cols in TABLES.items():
        lines = [f"  {c} {t}" for c, t in cols]
        lines.append(f"  PRIMARY KEY ({', '.join(PRIMARY_KEYS[table])})")
        if table == "measures":
            lines.append(f"  CHECK (measure IN ({measures}))")
            lines.append(f"  CHECK ((measure || ':' || term) IN ({pairs}))")
        out.append(f"CREATE TABLE {table} (\n" + ",\n".join(lines) + "\n);")
        out.append("")
    return "\n".join(out)


def main():
    (config.ROOT / "schema.sql").write_text(render(), encoding="utf-8")


if __name__ == "__main__":
    main()
